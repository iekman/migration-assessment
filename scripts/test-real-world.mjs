#!/usr/bin/env node
// Regression + discovery suite run against real-world material (public
// rules files, real Cloud Functions names/triggers from
// firebase/functions-samples) instead of only our own hand-written
// fixtures. See fixtures/real-world-rules/ and fixtures/real-world-functions.json
// for provenance notes on each case.
import { readFileSync, readdirSync, unlinkSync } from "node:fs";
import { strict as assert } from "node:assert";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { parseCollectionTree } from "../dist/rulesParser.js";
import { classify } from "../dist/collectors/functions.js";
import { deriveServerpodStrengths } from "../dist/strengths.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const fixturesDir = path.join(__dirname, "..", "fixtures");

let failures = 0;

// --- Suite 1: rules parser, strict pass/fail -------------------------------
// Expected output recorded here was generated by running the parser
// against each file and hand-verifying the result makes sense for that
// file's actual rules (see the conversation this was built in for the
// line-by-line trace) - this is a regression test, not a guess.
const RULES_EXPECTATIONS = {
  "29ki-29k.rules": {
    topLevelCollections: ["sessions"],
    subcollections: { sessions: ["state"] },
    tenantHints: [],
    maxNestingDepth: 2,
  },
  "firebase-quickstart-js.rules": {
    topLevelCollections: ["restaurants"],
    subcollections: { restaurants: ["ratings"] },
    tenantHints: [],
    maxNestingDepth: 2,
  },
  "satansdeer-firebase-albums.rules": {
    topLevelCollections: [],
    subcollections: {},
    tenantHints: [],
    maxNestingDepth: 0,
  },
  "synthetic-block-comment-and-deep-nesting.rules": {
    topLevelCollections: ["orgs"],
    subcollections: { orgs: ["teams"], teams: ["members"] },
    // Correct, not a bug: "orgId" is a wildcard name here, not a field/claim,
    // but it legitimately matches the tenant-hint pattern - a reasonable
    // thing to flag either way, so the heuristic isn't wrong to catch it.
    tenantHints: ["orgId"],
    maxNestingDepth: 3,
  },
};

console.log("=== Rules parser: real-world + authored edge cases ===\n");
const rulesDir = path.join(fixturesDir, "real-world-rules");
for (const file of readdirSync(rulesDir).sort()) {
  const text = readFileSync(path.join(rulesDir, file), "utf-8");
  const result = parseCollectionTree(text);
  const expected = RULES_EXPECTATIONS[file];
  if (!expected) {
    console.log(`?  ${file}: no expectation recorded - add one to this script`);
    failures++;
    continue;
  }
  try {
    assert.deepEqual(result.topLevelCollections.sort(), expected.topLevelCollections.sort());
    assert.deepEqual(result.subcollections, expected.subcollections);
    assert.deepEqual(result.tenantHints.sort(), expected.tenantHints.sort());
    assert.equal(result.maxNestingDepth, expected.maxNestingDepth);
    console.log(`OK ${file}`);
  } catch (err) {
    failures++;
    console.log(`FAIL ${file}`);
    console.log(`     expected: ${JSON.stringify(expected)}`);
    console.log(`     actual:   ${JSON.stringify(result)}`);
  }
}

// --- Suite 2: Cloud Functions trigger classification, coverage report ------
// Not pass/fail against "nameOnly" - the whole point is to measure how
// often the naming-convention fallback gets it right on real names,
// not to assert it always does. "withMetadata" IS asserted strictly,
// since that path is just a direct field lookup with no guessing in it.
console.log("\n=== Cloud Functions classify(): real-world names/triggers ===\n");
const { functions } = JSON.parse(readFileSync(path.join(fixturesDir, "real-world-functions.json"), "utf-8"));

let nameOnlyCorrect = 0;
for (const f of functions) {
  const withMetadata = classify(f.withMetadata);
  const nameOnly = classify(f.nameOnly);

  try {
    assert.equal(withMetadata.triggerType, f.expectedTrigger);
  } catch {
    failures++;
    console.log(`FAIL ${f.name}: withMetadata expected "${f.expectedTrigger}", got "${withMetadata.triggerType}"`);
  }

  const nameOnlyHit = nameOnly.triggerType === f.expectedTrigger;
  if (nameOnlyHit) nameOnlyCorrect++;
  console.log(
    `${nameOnlyHit ? "hit " : "miss"} ${f.name} (${f.source}, real builder: ${f.realBuilder}) ` +
      `- expected "${f.expectedTrigger}", name-only guess: "${nameOnly.triggerType}"` +
      (f.note ? ` [${f.note}]` : ""),
  );
}
console.log(
  `\nName-only classification: ${nameOnlyCorrect}/${functions.length} correct on real-world function names.`,
);

// --- Suite 3: deriveServerpodStrengths, run through the REAL pipeline ------
// strengths.ts detects conditions by pattern-matching finding.summary text
// produced by the collectors - a purely presentational change to a
// collector's summary wording can silently break that matching with no
// type error, since both sides are just strings (this exact thing happened
// once already: a pluralization pass removed every literal "(s)" from
// summaries, and strengths.ts's regexes - written against the old format -
// stopped matching anything, silently dropping two conditional bullets).
// Running the actual CLI against real fixtures and deriving strengths from
// its real JSON output, rather than hand-building a fake report here, is
// what makes this test actually catch that: it exercises the real string
// contract between collectors and strengths.ts, not a reimplementation of it.
console.log("\n=== deriveServerpodStrengths: against the real pipeline's own output ===\n");
const rootDir = path.join(__dirname, "..");

function strengthsFor(fixtureBase) {
  const outBase = path.join(fixturesDir, `.tmp-${fixtureBase}`);
  execFileSync(
    "node",
    [
      "dist/cli.js",
      "--mock",
      "--fixture-data",
      `fixtures/${fixtureBase}.json`,
      "--config",
      `fixtures/${fixtureBase}.config.json`,
      "--out",
      outBase,
      "--format",
      "json",
    ],
    { cwd: rootDir, stdio: "pipe" },
  );
  const report = JSON.parse(readFileSync(`${outBase}.json`, "utf-8"));
  return deriveServerpodStrengths(report).join("\n---\n");
}

const STRENGTHS_EXPECTATIONS = [
  {
    fixture: "example-messy",
    mustContain: ["5 background-triggered functions", "request/response-style functions port close to one-to-one"],
    mustNotContain: ["Firebase bills per read, write, and function invocation"], // the untriggered baseline should not also appear
  },
  {
    fixture: "example-simple",
    mustContain: ["Firebase bills per read, write, and function invocation"], // no background triggers -> baseline cost bullet
    mustNotContain: ["background-triggered functions", "request/response-style functions port close to one-to-one"],
  },
];

for (const { fixture, mustContain, mustNotContain } of STRENGTHS_EXPECTATIONS) {
  const text = strengthsFor(fixture);
  let ok = true;
  for (const phrase of mustContain) {
    if (!text.includes(phrase)) {
      ok = false;
      failures++;
      console.log(`FAIL ${fixture}: expected a strength containing "${phrase}", found none`);
    }
  }
  for (const phrase of mustNotContain) {
    if (text.includes(phrase)) {
      ok = false;
      failures++;
      console.log(`FAIL ${fixture}: did not expect any strength to contain "${phrase}", but one did`);
    }
  }
  if (ok) console.log(`OK ${fixture}`);
}

for (const { fixture } of STRENGTHS_EXPECTATIONS) {
  try {
    unlinkSync(path.join(fixturesDir, `.tmp-${fixture}.json`));
  } catch {
    // best-effort cleanup only
  }
}

console.log(failures > 0 ? `\n${failures} failure(s).` : "\nAll strict assertions passed.");
process.exit(failures > 0 ? 1 : 0);
